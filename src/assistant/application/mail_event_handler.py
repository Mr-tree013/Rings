"""The first real `EventHandler`: classify one synchronized message (ADR-0021).

```text
InboundEvent(mail.message.received)
        │ payload: {account_id, mail_message_id}
        ▼
resolve the stable MailMessage ── verify the event link ──► mismatch: retry
        │
        ▼
ensure deterministic thread (code, never a model)
        │
        ▼
bounded untrusted thread context
        │
        ├── stored analysis with the same fingerprint? ──► reuse it, no model call
        ▼
StructuredModel (closed schema) ──► local semantic validation ──► MailAnalysis
```

The handler writes exactly one kind of durable state: an analysis. It cannot create a task, a
case, a deadline, a calendar event, a notification or an outbound message, because nothing in
its imports can — and because the schema it sends has nowhere to put one.

Failure classification is deliberately split. A provider that is throttled, briefly down or
answering with unusable JSON is *retryable*: the next attempt may succeed, and the existing
EventWorker already bounds how many attempts are spent. A provider that rejects the credential,
has no balance, or refuses the request as malformed will not behave differently the second time,
so it is a `PermanentEventError` and the event dead-letters immediately instead of burning the
retry budget. Either way the mail itself is untouched: a model failure is never a reason for a
stored message to change or disappear.
"""

